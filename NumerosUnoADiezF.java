public class NumerosUnoADiezF {
    public static void main (String [] args) {

        int i;

        for (i=1; i<=10; i++) { /* Números uqe recorre el FOR, empieza en 1 y termina en 10, cuando llega a 10, lo imprime y termina el FOR: */
            System.out.println(i);
        }
        
        System.out.println("Fuera del for: " + i);
    }
}
